#!/usr/bin/env node
// Generates the SDK API reference from exported declarations in src/.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'src');
const output = path.join(root, 'docs', 'api-reference.md');
const declarations = /export\s+(?:declare\s+)?(?:abstract\s+)?(class|interface|type|enum|function|const)\s+([A-Za-z0-9_]+)/g;
const entries = [];

for (const file of readdirSync(sourceDir).filter(name => name.endsWith('.ts')).sort()) {
  const source = readFileSync(path.join(sourceDir, file), 'utf8');
  for (const match of source.matchAll(declarations)) entries.push({ file, kind: match[1], name: match[2] });
}

const lines = [
  '# @quorum/sdk API reference', '',
  '> Generated by `npm run docs` from the exported declarations in `sdk/src`.', '',
  `Generated entries: ${entries.length}`, '',
  '| Export | Kind | Source |', '| --- | --- | --- |',
  ...entries.map(entry => `| \`${entry.name}\` | ${entry.kind} | [\`${entry.file}\`](../src/${entry.file}) |`), '',
];
const generated = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    console.error('docs/api-reference.md is stale; run `npm run docs`');
    process.exit(1);
  }
} else {
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, generated);
}
